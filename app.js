function initAppointmentForm() {
  const form = document.getElementById('appointment-form');
  const error = document.getElementById('form-error');
  const success = document.getElementById('form-success');
  const dateInput = form ? form.querySelector('[name="preferredDate"]') : null;
  if (!form) return;

  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const localDateIso = (date) => {
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, '0');
    const day = String(date.getDate()).padStart(2, '0');
    return `${year}-${month}-${day}`;
  };
  const todayIso = localDateIso(today);
  if (dateInput) dateInput.min = todayIso;

  form.addEventListener('submit', async (event) => {
    event.preventDefault();
    error.textContent = '';
    success.textContent = '';

    const data = new FormData(form);
    const fullName = String(data.get('fullName') || '').trim();
    const mobileNumber = String(data.get('mobileNumber') || '').trim();
    const emailAddress = String(data.get('emailAddress') || '').trim();
    const preferredDate = String(data.get('preferredDate') || '').trim();
    const preferredTimeRange = String(data.get('preferredTimeRange') || '').trim();
    const complaints = String(data.get('complaints') || '').trim();
    const mobileValid = /^(?:\+?91[-\s]?)?[6-9]\d{9}$/.test(mobileNumber);
    const emailValid = /^\S+@\S+\.\S+$/.test(emailAddress);
    const selectedDate = preferredDate ? new Date(`${preferredDate}T00:00:00`) : null;

    if (!fullName) return error.textContent = 'Full name is required.';
    if (!mobileValid) return error.textContent = 'Enter a valid Indian mobile number.';
    if (!emailValid) return error.textContent = 'Enter a valid email address.';
    if (!preferredDate) return error.textContent = 'Preferred date is required.';
    if (!selectedDate || selectedDate < today) return error.textContent = 'Please select today or an upcoming date.';
    if (!preferredTimeRange) return error.textContent = 'Preferred time range is required.';
    if (!complaints) return error.textContent = 'Complaints field is required.';

    const bodyText = [
      `Patient Name: ${fullName}`,
      `Mobile Number: ${mobileNumber}`,
      `Email: ${emailAddress}`,
      `Preferred Date: ${preferredDate}`,
      `Preferred Time Range: ${preferredTimeRange}`,
      `Complaints: ${complaints}`
    ].filter(Boolean).join('\n');

    const subject = `Appointment Enquiry - ${fullName}`;
    const mailtoUrl = `mailto:${SITE.email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(bodyText)}`;
    const submitButton = form.querySelector('button[type="submit"]');
    if (submitButton) submitButton.disabled = true;

    try {
      const response = await fetch('https://api.web3forms.com/submit', {
  method: 'POST',
  headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
  body: JSON.stringify({
    access_key: "73f5ed3d-ab9d-4add-a20d-624833af186e",
    subject: subject,
    from_name: fullName,
    name: fullName,
    mobile: mobileNumber,
    email: emailAddress,
    preferred_date: preferredDate,
    preferred_time_range: preferredTimeRange,
    complaints: complaints
  })
});
      if (!response.ok) throw new Error('Email service failed');
      success.textContent = 'Thank you for contacting Dr. Ajeya Deshpande. Your appointment request has been sent to the clinic email. Our team will contact you shortly to confirm your appointment.';
      form.reset();
      if (dateInput) dateInput.min = todayIso;
    } catch (submitError) {
      success.textContent = 'Your email app will open with the appointment request. Please press Send to complete it.';
      window.location.href = mailtoUrl;
    } finally {
      if (submitButton) submitButton.disabled = false;
    }
  });
}

